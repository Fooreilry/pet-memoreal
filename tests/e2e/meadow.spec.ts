import { clickGardenControl, dismissGardenTools, ensureGardenControl } from './helpers/garden-controls'
import { openMemorialStory } from './helpers/memorial'
import { visitLocale } from './helpers/locale'
import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function clearPreview(page: Page) {
  await dismissGardenTools(page)
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur() })
  await page.mouse.move(0, 0)
  await expect(page.getByTestId('memorial-summary')).toHaveCount(0)
}

test.beforeEach(async ({ page }) => {
  await page.route('**/api/gardens/*/memorials', route => route.fulfill({ json: [] }))
})

test('the flowering meadow opens from the overview and its plants leave all memorials reachable', async ({ page, isMobile }, testInfo) => {
  const errors: string[] = []
  const images: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.resourceType() === 'image') images.push(request.url()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await visitLocale(page, '/gardens', 'ru')
  const meadow = page.getByTestId('garden-choice-meadow')
  await expect(meadow).toBeVisible()
  await clearPreview(page)
  await page.locator('canvas').screenshot({ path: testInfo.outputPath('meadow-selection.png') })
  if (isMobile) await meadow.tap()
  else await meadow.click()
  await expect(page).toHaveURL(/\/gardens\?garden=meadow$/)
  const scene = page.locator('.canvas-wrapper')
  const canvas = page.locator('canvas')
  await expect(scene).toHaveAttribute('data-state', 'ready')
  await expect(scene).toHaveAttribute('data-motion', 'paused')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Луг')
  await expect(canvas).toHaveAccessibleName(/Сад «Луг»/)
  await expect(page.locator('.memorial-hit')).toHaveCount(12)
  await expect(page.locator('.memorial-empty')).toHaveCount(8)
  await expect(page.locator('.memorial-hit[data-monument-kind]')).toHaveCount(4)
  await clearPreview(page)
  await canvas.screenshot({ path: testInfo.outputPath('meadow-garden.png') })
  await page.getByTestId('garden-zoom-in').click()
  await expect(scene).toHaveAttribute('data-zoom', '1.250')
  await scene.focus()
  const overflow = await scene.evaluate((element) => {
    const view = element as HTMLElement
    const bounds = view.getBoundingClientRect()
    const scale = Number(view.dataset.projectionScale) * Number(view.dataset.zoom)
    return { x: Number(view.dataset.worldWidth) * scale > bounds.width + 1, y: Number(view.dataset.worldHeight) * scale > bounds.height + 1 }
  })
  expect(overflow.x || overflow.y).toBe(true)
  const axis = overflow.x ? 'x' : 'y'
  const previous = Number(await scene.getAttribute(`data-camera-${axis}`))
  await page.keyboard.press(overflow.x ? 'ArrowRight' : 'ArrowDown')
  expect(Number(await scene.getAttribute(`data-camera-${axis}`))).toBeLessThan(previous)
  for (const place of [1, 2, 6, 12]) {
    const stone = page.getByTestId(`memorial-meadow-${place}`)
    await stone.focus()
    await expect(stone).toBeInViewport()
    await openMemorialStory(page, stone, isMobile)
    await expect(page.getByRole('dialog').locator('.memorial-location')).toContainText(`Место ${place}`)
    await page.getByTestId('memorial-detail-return').click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(stone).toBeFocused()
  }
  await page.getByTestId('memorial-meadow-1').focus()
  await clearPreview(page)
  await canvas.screenshot({ path: testInfo.outputPath('meadow-detail.png') })
  // Removing the right-hand water body must preserve the complete neighboring garden.
  await page.getByTestId('garden-next').click()
  await expect(page).toHaveURL(/garden=lake$/)
  await expect(scene).toHaveAttribute('data-state', 'ready')
  await expect(page.locator('.memorial-hit')).toHaveCount(10)
  await expect(page.locator('.memorial-empty')).toHaveCount(6)
  await clearPreview(page)
  await canvas.screenshot({ path: testInfo.outputPath('lake-planted-bank.png') })
  for (const place of [1, 2, 5, 10]) {
    const stone = page.getByTestId(`memorial-lake-${place}`)
    await stone.focus()
    await expect(stone).toBeInViewport()
    await openMemorialStory(page, stone, isMobile)
    await expect(page.getByRole('dialog').locator('.memorial-location')).toContainText(`Место ${place}`)
    await page.getByTestId('memorial-detail-return').click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  expect(images.every(url => new URL(url).origin === new URL(page.url()).origin)).toBe(true)
  expect(errors).toEqual([])
})

test('meadow insects obey pause and reduced motion while rotation and a free place remain usable', async ({ page, isMobile }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.route('**/api/auth/get-session', route => route.fulfill({ json: null }))
  await visitLocale(page, '/gardens?garden=meadow', 'en')
  const scene = page.locator('.canvas-wrapper')
  const canvas = page.locator('canvas')
  await expect(scene).toHaveAttribute('data-state', 'ready')
  await expect(canvas).toHaveAccessibleName(/Meadow garden/)
  await expect(scene).toHaveAttribute('data-motion', 'running')
  await clearPreview(page)
  const moving = await canvas.screenshot()
  await expect.poll(async () => Buffer.compare(moving, await canvas.screenshot())).not.toBe(0)
  const first = page.getByTestId('memorial-meadow-1')
  await first.focus()
  await expect(first).toBeInViewport()
  await openMemorialStory(page, first, isMobile)
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(scene).toHaveAttribute('data-motion', 'paused')
  await page.getByTestId('memorial-detail-return').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(scene).toHaveAttribute('data-motion', 'running')
  const pause = page.getByTestId('garden-motion')
  await clickGardenControl(page, 'garden-motion')
  await dismissGardenTools(page)
  await expect(scene).toHaveAttribute('data-motion', 'paused')
  await clearPreview(page)
  const still = await canvas.screenshot()
  await page.waitForTimeout(250)
  expect(Buffer.compare(still, await canvas.screenshot())).toBe(0)
  for (const size of [{ width: 360, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(size)
    await expect.poll(() => canvas.evaluate(element => {
      const surface = element as HTMLCanvasElement
      const resolution = Math.min(devicePixelRatio || 1, 2)
      return Math.abs(surface.width - surface.clientWidth * resolution) + Math.abs(surface.height - surface.clientHeight * resolution)
    })).toBeLessThan(3)
    await expect(page.locator('.memorial-hit')).toHaveCount(12)
    await expect(scene).toHaveAttribute('data-motion', 'paused')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight)).toBe(true)
    await clearPreview(page)
    await canvas.screenshot({ path: testInfo.outputPath(`meadow-${size.width}.png`) })
  }
  await page.getByTestId('garden-next').click()
  await expect(scene).toHaveAttribute('data-motion', 'paused')
  await expect(page.locator('.memorial-hit')).toHaveCount(10)
  await page.getByTestId('garden-previous').click()
  await expect(page).toHaveURL(/garden=meadow$/)
  await ensureGardenControl(page, 'garden-motion')
  await expect(pause).toHaveAttribute('aria-pressed', 'true')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(pause).toHaveCount(0)
  await expect(scene).toHaveAttribute('data-motion', 'paused')
  await clearPreview(page)
  const reduced = await canvas.screenshot()
  await page.waitForTimeout(250)
  expect(Buffer.compare(reduced, await canvas.screenshot())).toBe(0)
  await page.getByTestId('garden-zoom-in').click()
  const empty = page.getByTestId('empty-meadow-3')
  await expect(empty).toBeEnabled()
  await empty.focus()
  await expect(empty).toBeInViewport()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  expect(new URL(page.url()).searchParams.get('redirect')).toBe('/memorials/new?garden=meadow&place=3')
  expect(errors).toEqual([])
})
